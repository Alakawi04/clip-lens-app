const LanguageContext = createContext(null);

// Exposed so the admin dashboard can list every editable text.
export const TRANSLATIONS = translations;

const EMPTY_OVERRIDES = {};

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const saved = typeof window !== 'undefined' ? localStorage.getItem('cliplens-lang') : null;
    return saved === 'ar' || saved === 'en' ? saved : 'en';
  });
  const [switching, setSwitching] = useState(false);
  const timers = useRef([]);

  const site = useOptionalSiteSettings();
  const overrides = site?.settings?.texts || EMPTY_OVERRIDES;

  const dir = lang === 'ar' ? 'rtl' : 'ltr';

  useEffect(() => {
    localStorage.setItem('cliplens-lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  // Swap the language behind a short animated curtain so the RTL flip is never jarring.
  const setLang = useCallback(
    (next) => {
      if (next === lang) return;
      timers.current.forEach(clearTimeout);
      setSwitching(true);
      timers.current = [
        window.setTimeout(() => setLangState(next), 420),
        window.setTimeout(() => setSwitching(false), 1050),
      ];
    },
    [lang]
  );

  useEffect(() => () => timers.current.forEach(clearTimeout), []);

  const t = useCallback(
    (key) => {
      const override = overrides[`${lang}.${key}`];
      if (override !== undefined && override !== '') return override;
      const dict = translations[lang] || translations.en;
      return dict[key] ?? translations.en[key] ?? key;
    },
    [lang, overrides]
  );

  const toggleLang = useCallback(() => {
    setLang(lang === 'en' ? 'ar' : 'en');
  }, [lang, setLang]);

  const value = useMemo(
    () => ({ lang, dir, t, toggleLang, setLang, switching, overrides }),
    [lang, dir, t, toggleLang, setLang, switching, overrides]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useI18n must be used within LanguageProvider');
  return ctx;
}